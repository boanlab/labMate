def enforce_count(text: str) -> str:
    """선언한 개수보다 많이 쓴 지적을 잘라낸다.

    프롬프트로 '판정: 보통 · 고칠 점 2개'를 선언시켜도 3개를 쓰는 일이 남는다.
    선언과 실제가 다르면 학생이 무엇을 믿어야 할지 헷갈리므로 서버에서 맞춘다.
    """
    import re

    m = re.search(r"판정[:：][^\n]*?고칠\s*점\s*(\d+)\s*개", text)
    if not m:
        return text
    limit = int(m.group(1))
    lines = text.split("\n")
    item = re.compile(r"^\s*(?:[*_~`]{0,2})(\d+)[).]")
    seen, cut = 0, None
    for i, ln in enumerate(lines):
        mm = item.match(ln)
        if not mm:
            continue
        seen += 1
        if seen > limit:
            cut = i
            break
    if cut is None:
        return text
    # 초과 항목부터 끝까지 버리되, 뒤에 붙는 '문체:' 줄과 총평은 살린다.
    keep = [ln for ln in lines[cut:]
            if re.match(r"^\s*(?:[*_~`]{0,2})(문체|총평)", ln.strip())]
    out = lines[:cut]
    if keep:
        out += [""] + keep
    return "\n".join(out).rstrip()
